    def __init__(
            self, model_name: str, base_url: str, api_key: str
            ) -> None:
        # base_url car url = f"{self.base_url}/chat/completions"
        self.model_name = model_name
        self.base_url = base_url.rstrip("/")
        base_url.rstrip("/")
        # S'il y a un ou plusieurs slashs à la fin, Python les retire.
        # permettra d'écrire proprement
        # url = f"{self.base_url}/chat/completions"
        self.api_key = api_key

