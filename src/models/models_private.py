from typing import Optional, Literal

from pydantic import BaseModel, Field


class LLMResponse(BaseModel):
    """Pydantic model representing a standardized response from an LLM."""

    text: str = Field(
        ...,
        description="Raw text generated by the model",
    )
    input_tokens: int = Field(
        ...,
        description="Tokens sent to the LLM for this step",
    )
    output_tokens: int = Field(
        ...,
        description="Tokens generated by the LLM for this step",
    )
    request_time_ms: float = Field(
        ...,
        description="Wall-clock time for the LLM API call in milliseconds",
    )
    api_url: str = Field(
        default="",
        description="Base URL of the LLM API endpoint",
    )
    model_name: str = Field(
        default="",
        description="Model identifier used for this step",
    )


class CodeExtractionResult(BaseModel):
    code: str = Field(..., description="Code to execute")
    source_format: Literal["markdown", "xml", "json", "react"] = Field(
        ..., description="Detected format of the LLM response"
    )
    truncated: bool = Field(
        default=False,
        description="True if the code block had no closing fence",
    )
    ignored_blocks: int = Field(
        default=0,
        description="Extra code blocks or tool calls that were not executed",
    )

    def feedback(self) -> str:
        """Build the message telling the LLM how its response was read.

        The subject requires explicit feedback when a response was malformed
        but interpreted anyway, so the LLM is never left guessing. The agent
        loop should add this message to the observation sent back to the LLM.

        Returns:
            One line per issue found (missing closing fence, extra blocks or
            tool calls ignored), or an empty string if the response was
            well-formed.
        """
        messages: list[str] = []
        if self.truncated:
            messages.append(
                "Warning: your code block had no closing ``` fence. It was "
                "interpreted anyway, from the opening fence up to "
                "<end_code> or the end of your response. Always close your "
                "code block with ``` before <end_code>."
            )
        if self.ignored_blocks:
            unit = (
                "code block" if self.source_format == "markdown"
                else "tool call"
            )
            messages.append(
                f"Warning: only your first {unit} was executed; "
                f"{self.ignored_blocks} other {unit}(s) were ignored. "
                f"Write exactly one {unit} per response, then wait for "
                "the observation."
            )
        return "\n".join(messages)


class ExecutionResult(BaseModel):
    """Result of code execution within the sandbox environment."""

    stdout: str = Field(
        default="",
        description="Standard output produced during code execution",
    )
    stderr: str = Field(
        default="",
        description="Standard error produced during code execution",
    )
    output: str = Field(
        default="",
        description="Combined or formatted output visible to the agent/user",
    )
    success: bool = Field(
        default=True,
        description="Whether the code executed without uncaught exceptions",
    )
    is_final_answer: bool = Field(
        default=False,
        description="Whether final_answer() was called during this execution",
    )
    final_answer_value: Optional[str] = Field(
        default=None,
        description="Argument passed to final_answer() if invoked",
    )
    truncated: bool = Field(
        default=False,
        description="Whether output was truncated due to length limits",
    )
    execution_time_ms: float = Field(
        default=0.0,
        description="Wall-clock execution time in milliseconds",
    )
    error: Optional[str] = Field(
        default=None,
        description="Error message or exception traceback if execution failed",
    )
